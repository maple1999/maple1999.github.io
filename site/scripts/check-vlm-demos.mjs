/** Exercise both method illustrations without calling a model or sending visit beacons. */
import assert from 'node:assert/strict';
import { existsSync, mkdirSync } from 'node:fs';
import puppeteer from 'puppeteer-core';
const executablePath = ['C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', 'C:/Program Files/Microsoft/Edge/Application/msedge.exe'].find(existsSync);
const base = process.argv[2] || 'http://localhost:4321';
const browser = await puppeteer.launch({ executablePath, headless: true, pipe: true });
const errors = [];
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
mkdirSync('.shots/vlm', { recursive: true });
try {
  const page = await browser.newPage();
  page.on('pageerror', e => errors.push(e.message));
  await page.setRequestInterception(true);
  page.on('request', r => r.url().includes('/_visit') ? r.respond({ status: 204 }) : r.continue());
  await page.setCacheEnabled(false);
  await page.emulateMediaFeatures([{ name: 'prefers-reduced-motion', value: 'reduce' }]);
  const query = 'vlm-demo[data-mode="query"]';
  const route = 'vlm-demo[data-mode="routing"]';
  for (const width of [1440, 375, 320]) for (const lang of ['en', 'zh']) {
    await page.setViewport({ width, height: 1100 });
    await page.goto(base + (lang === 'en' ? '/academic/' : '/academic/zh/'), { waitUntil: 'networkidle0' });
    await page.waitForFunction(() => document.querySelectorAll('vlm-demo[data-enhanced]').length === 2);
    await page.$eval(query, el => el.scrollIntoView({ block: 'center', behavior: 'instant' }));
    await page.waitForFunction(sel => document.querySelector(sel).dataset.running === 'true', {}, query);
    assert.equal(await page.$eval(query + ' .demo-motion-mark i', el => getComputedStyle(el).animationName), 'none');
    await page.click(query + ' [data-play]');
    assert.equal(await page.$eval(query, el => el.dataset.running), 'false');
    await page.click(query + ' [data-scope-choice="1"]');
    await page.focus(query + ' [data-next]');
    for (let i = 0; i < 3; i++) await page.keyboard.press('Enter');
    assert.equal(await page.$eval(query, el => el.dataset.stage), '3');
    assert.equal(await page.$$eval(query + ' .query-answers [data-in-scope="true"]', els => els.length), 1);
    assert.equal(await page.$$eval(query + ' .demo-video .selected', els => els.length), 2);
    await page.click(query + ' [data-scope-choice="3"]');
    assert.equal(await page.$$eval(query + ' .query-answers [data-in-scope="true"]', els => els.length), 3);
    assert.equal(await page.$$eval(query + ' .demo-video .selected', els => els.length), 4);
    assert.equal(await page.$eval(query + ' .encoding-track i', el => getComputedStyle(el).transform), 'matrix(1, 0, 0, 1, 0, 0)');
    await (await page.$(query)).screenshot({ path: `.shots/vlm/query-${lang}-${width}.png` });
    await page.click(route + ' [data-route-choice="confident"]');
    for (let i = 0; i < 3; i++) await page.click(route + ' [data-next]');
    assert.equal(await page.$eval(route + ' [data-branch="confident"]', el => el.dataset.selected), 'true');
    assert.equal(await page.$eval(route + ' [data-extra="true"]', el => getComputedStyle(el).opacity), '0.15');
    await page.click(route + ' [data-route-choice="uncertain"]');
    assert.equal(await page.$eval(route + ' [data-branch="uncertain"]', el => el.dataset.selected), 'true');
    assert.equal(await page.$eval(route + ' [data-extra="true"]', el => getComputedStyle(el).opacity), '1');
    assert.equal(await page.$eval(route, el => el.dataset.running), 'false');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await (await page.$(route)).screenshot({ path: `.shots/vlm/routing-${lang}-${width}.png` });
    console.log(`PASS controls, keyboard, reduced motion, layout: ${lang} ${width}`);
  }
  await page.emulateMediaFeatures([{ name: 'prefers-reduced-motion', value: 'no-preference' }]);
  await page.setViewport({ width: 1440, height: 1100 });
  await page.goto(base + '/academic/', { waitUntil: 'networkidle0' });
  await page.$eval(query, el => el.scrollIntoView({ block: 'center', behavior: 'instant' }));
  await page.waitForFunction(sel => document.querySelector(sel).dataset.running === 'true', {}, query);
  const firstStage = await page.$eval(query, el => el.dataset.stage);
  await page.waitForFunction((sel, stage) => document.querySelector(sel).dataset.stage !== stage, { timeout: 6000 }, query, firstStage);
  await page.click(query + ' [data-play]');
  const pausedStage = await page.$eval(query, el => el.dataset.stage);
  await wait(3400);
  assert.equal(await page.$eval(query, el => el.dataset.stage), pausedStage);
  await page.click(query + ' [data-play]');
  await page.$eval('#contact', el => el.scrollIntoView({ behavior: 'instant' }));
  await page.waitForFunction(() => [...document.querySelectorAll('vlm-demo')].every(el => el.dataset.running === 'false'));
  await page.evaluate(() => dispatchEvent(new Event('beforeprint')));
  assert(await page.$$eval('vlm-demo', els => els.every(el => el.dataset.stage === '3')));
  await page.evaluate(() => dispatchEvent(new Event('afterprint')));
  await page.setJavaScriptEnabled(false);
  await page.goto(base + '/academic/', { waitUntil: 'networkidle0' });
  assert.equal(await page.$$eval('vlm-demo', els => els.length), 2);
  assert(await page.$$eval('vlm-demo [data-controls]', els => els.every(el => !el.checkVisibility())));
  assert(await page.$$eval('vlm-demo .evidence-core', els => els.every(el => el.checkVisibility())));
  assert.deepEqual(errors, []);
  console.log('PASS autoplay, pause, offscreen suspension, print, no-JS, browser errors');
} finally { await browser.close(); }
